export const getStaticProps: GetStaticProps<{ venue: BookingVenue }> = async (ctx) => {
  const slug = String(ctx.params?.slug);
  const venue = BOOKING_BY_SLUG[BOOKING_SLUG_BY_URL[slug] ?? slug];
  if (!venue) return { notFound: true };
  return { props: { venue } };
};

