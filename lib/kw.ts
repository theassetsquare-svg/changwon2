// 업소명 키워드 문장 생성기.
// 각 업소 페이지 본문에 그 페이지의 가게이름을 정확히 1회씩 더 넣는 문장을 만든다.
// (도입부 1문장 + 마무리 1문장 = 페이지당 +2회)
// 문구는 슬러그 해시로 골라 40여 페이지가 같은 문장을 쓰지 않게 한다.
// ★타 가게이름은 결코 들어가지 않는다 — 인자로 받은 name 하나만 쓴다.

function pick<T>(slug: string, salt: number, arr: T[]): T {
  let h = salt * 2654435761;
  for (let i = 0; i < slug.length; i++) h = (h * 31 + slug.charCodeAt(i)) >>> 0;
  return arr[h % arr.length];
}

/** 도입부(직답 박스 직전/직후)에 붙는 한 문장. name 1회. */
export function kwLead(name: string, region: string, slug: string): string {
  return pick(slug, 1, [
    `${name} 부킹이 궁금해서 들어오셨다면, 아래 순서를 그대로 따라 읽으면 됩니다.`,
    `이 글은 ${name}를 처음 찾는 분을 기준으로 정리했습니다.`,
    `${name} 방문 전에 한 번 훑어두면 좋은 내용을 순서대로 담았습니다.`,
    `${name}에서 저녁이 어떻게 흘러가는지부터 차근히 보겠습니다.`,
    `${region}에서 ${name}를 찾는 분들이 가장 먼저 궁금해하는 부분부터 짚습니다.`,
    `${name} 이용이 처음이라면 이 순서만 기억해도 충분합니다.`,
    `${name} 관련해 자주 들어오는 질문을 한 페이지에 모았습니다.`,
    `${name}를 검색해서 들어오셨다면 이 문서가 그 답입니다.`,
  ]);
}

/** 마무리(요약 직후)에 붙는 한 문장. name 1회. */
export function kwClose(name: string, slug: string): string {
  return pick(slug, 2, [
    `${name}를 찾는다면 위 순서만 기억해도 그날 저녁이 한결 매끄러워집니다.`,
    `결국 ${name}에서도 중요한 건 이미 돌고 있는 흐름에 정확히 얹히는 일입니다.`,
    `${name} 방문을 앞두고 있다면 이 정리만 다시 한 번 확인해 보세요.`,
    `${name}의 홀도 같은 원리로 돌아갑니다.`,
    `${name}를 두고 고민 중이라면 위에 정리한 세 가지부터 챙기면 됩니다.`,
    `${name} 이용 흐름은 이 순서를 크게 벗어나지 않습니다.`,
    `${name}에 대해 더 알고 싶다면 이 페이지의 정리를 기준으로 삼으면 됩니다.`,
    `${name}를 처음 가는 날에도 이 세 가지면 충분합니다.`,
  ]);
}
