/**
 * 2026-09-25 전부10 — 장부(data/shops)에 확인 값이 없는 사실을 글에서 단정하는 문장을 뺀다
 * (「확인 안 된 값(가까운 역·주차·요금 등)은 쪽에서 뺀다」).
 *  · 시각(영업시간) — 장부에 영업시간이 있는 가게는 부르는 쪽이 이 거름을 건너뛴다
 *  · 가까운 역 — 장부에 역 칸이 없으므로 모든 가게에서 뺀다
 *  · 「주소가 확인되지 않았다」 — 장부에 주소가 확인된 가게는 옛 문장이 사실과 어긋나므로 뺀다
 * 제목줄처럼 문장이 하나뿐이면 「—」 앞 머리만 남기고, 그것도 걸리면 빈 글자를 돌려준다(부르는 쪽이 대신 말을 넣는다).
 */
const 시각말 = /(\d{1,2}\s*시(?!간)|\d{1,2}:\d{2}|오후\s*\d|저녁\s*\d|새벽\s*\d|아침\s*\d|밤\s*\d|(한|두|세|네|다섯|여섯|일곱|여덟|아홉|열|열한|열두)\s*시(?!간|작|절|장|대|내|외|청|민)|열\s*시간|자정)/;
const 역말 = /[가-힣]{1,5}(?<![지구영권광전성])역(에서|까지|과|와|이|은|을|\s*\d+번|\s*출구|\s*방면|\s*쪽|\s*하나|\s*인근|\s*근처)/;
const 주소부정말 = /((상세\s*)?주소|번지)[^.]{0,40}(확인되지 않|적지 않|싣지 않|비워)|같은 이름으로 여러 (곳|업소)|교차 확인되지 않아 (이 페이지에는 )?적지 않았/;
function 거름(t: string, 말들: RegExp[]): string {
  const 원 = String(t ?? "");
  if (!말들.some((re) => re.test(원))) return 원;
  const 남은 = 원.split(/(?<=[.!?。])\s+/).filter((s) => !말들.some((re) => re.test(s))).join(" ").trim();
  if (남은) return 남은;
  const 머리 = 원.split(/\s[—–-]\s|:\s/)[0].trim();
  return 머리 && 머리 !== 원 && !말들.some((re) => re.test(머리)) ? 머리 : "";
}
/** 장부 확인 여부에 맞춰 거른다 — 시간됨: 영업시간 확인 값 있음 · 주소됨: 주소 확인 값 있음 */
export function 미확인거름(t: string, { 시간됨, 주소됨 }: { 시간됨: boolean; 주소됨: boolean }): string {
  const 말들 = [역말];
  if (!시간됨) 말들.push(시각말);
  if (주소됨) 말들.push(주소부정말);
  return 거름(t, 말들);
}
